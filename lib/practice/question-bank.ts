export function getQuestionsByFilter(filter: {
  examId?: string;
  subjectId?: string;
  topicId?: string;
  isPyq?: boolean;
  limit?: number;
}): Question[] {
  let list = VERIFIED_QUESTION_BANK;
  if (filter.examId) {
    list = list.filter((q) => q.examId === filter.examId);
  }
  if (filter.subjectId) {
    list = list.filter((q) => q.subjectId === filter.subjectId);
  }
  if (filter.topicId) {
    list = list.filter((q) => q.topicId === filter.topicId);
  }
  if (filter.isPyq !== undefined) {
    list = list.filter((q) => q.isPyq === filter.isPyq);
  }
  if (filter.limit && filter.limit > 0) {
    return list.slice(0, filter.limit);
  }
  return list;
}
